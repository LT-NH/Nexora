"""Nexora - Natural Language BI Assistant (AI Agent).

Answers business questions in Chinese by:

1. Detecting the user's intent with lightweight keyword rules (no external
   API required for basic operation);
2. Querying the actual database (Order / OrderItem / Product / Refund /
   Customer) scoped to the workspace via SQLAlchemy;
3. Returning a structured dict the frontend renders as text + data table +
   simple chart, together with an actionable suggestion.

When ``settings.QWEN_API_KEY`` is configured, the rule-based answer is
upgraded with a natural-language response generated by Qwen (通义千问).
Any failure while calling Qwen falls back to the deterministic rule-based
answer so the endpoint always returns something useful.
"""

import json
from datetime import datetime, timedelta, timezone
from typing import Any

import httpx
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.models.customer import Customer
from app.models.order import Order, OrderItem, OrderStatus
from app.models.product import Product
from app.models.refund import Refund, RefundStatus
from app.utils.logging import get_logger

logger = get_logger(__name__)

# DashScope non-compatible mode text-generation endpoint.
_QWEN_GENERATION_URL = (
    "https://dashscope.aliyuncs.com/api/v1/services/aigc/text-generation/generation"
)

# Order statuses excluded from "valid" revenue / order statistics.
_EXCLUDED_STATUSES = [OrderStatus.CANCELLED, OrderStatus.REFUNDED]


def _money(value: float) -> str:
    """Format a monetary value as ¥ with 2 decimals."""
    return f"¥{value:,.2f}"


def _round2(value: float) -> float:
    """Round a float to 2 decimal places."""
    return round(value, 2)


async def _call_qwen_generation(
    system: str, prompt: str, temperature: float = 0.5
) -> str | None:
    """Call the Qwen text-generation API.

    Returns the assistant's text content, or ``None`` when no API key is
    configured / the request fails, so callers can fall back to rule-based
    output.
    """
    key = settings.QWEN_API_KEY
    if not key:
        return None

    payload = {
        "model": settings.QWEN_MODEL,
        "input": {
            "messages": [
                {"role": "system", "content": system},
                {"role": "user", "content": prompt},
            ]
        },
        "parameters": {"temperature": temperature, "result_format": "message"},
    }
    try:
        async with httpx.AsyncClient(timeout=30) as client:
            resp = await client.post(
                _QWEN_GENERATION_URL,
                headers={
                    "Authorization": f"Bearer {key}",
                    "Content-Type": "application/json",
                },
                json=payload,
            )
            data = resp.json()
            if resp.status_code != 200:
                logger.warning(
                    "Qwen generation failed (%s): %s", resp.status_code, data
                )
                return None
            content = (
                data.get("output", {})
                .get("choices", [{}])[0]
                .get("message", {})
                .get("content")
            )
            if not content:
                content = data.get("output", {}).get("text")
            return content.strip() if content else None
    except Exception as e:  # noqa: BLE001 - deliberate broad fallback
        logger.warning("Qwen generation call failed: %s", e)
        return None


class BIAgent:
    """BI agent that answers business questions from the real database."""

    # Intent detection keywords. Order matters: more specific intents are
    # checked first so e.g. "退款率高的订单" resolves to refund_rate, not
    # order_count.
    INTENT_KEYWORDS: dict[str, tuple[str, ...]] = {
        "churn_customers": ("流失", "沉睡", "未复购", "没再买", "很久没买", "不活跃", "唤回", "唤醒"),
        "refund_rate": ("退款", "退货", "退单", "退款率", "退货率"),
        "top_products": ("卖得最好", "爆款", "top", "最畅销", "热销", "销售排行", "销量最高", "卖得最多", "买得最多", "买的最多", "购买最多"),
        "low_stock": ("库存不足", "缺货", "预警", "库存告急", "快卖完", "补货", "库存低"),
        "product_list": ("有哪些商品", "商品列表", "什么商品", "商品清单", "产品列表", "商品有哪些", "看看商品", "商品都有"),
        "order_list": ("最近订单", "订单列表", "订单明细", "最新订单", "看看订单", "有哪些订单"),
        "refund_list": ("退款列表", "退款记录", "有哪些退款", "看看退款"),
        "customer_list": ("有哪些客户", "客户列表", "客户名单", "看看客户"),
        "customer_insight": ("复购", "回头客", "会员", "客户分析", "客户画像"),
        "revenue_summary": ("营收", "收入", "销售额", "卖了多少钱", "赚了多少", "营业额", "gmv", "卖了"),
        "order_count": ("多少单", "单量", "下单量", "几单", "订单数", "订单"),
    }

    # ------------------------------------------------------------------
    # Intent parsing
    # ------------------------------------------------------------------

    @staticmethod
    def detect_intent(question: str) -> str:
        """Map a free-text question to a known BI intent (keyword rules)."""
        q = question.lower()
        for intent, keywords in BIAgent.INTENT_KEYWORDS.items():
            if any(k in q for k in keywords):
                return intent
        return "default"

    # ------------------------------------------------------------------
    # Natural-language enhancement (Qwen, optional)
    # ------------------------------------------------------------------

    @staticmethod
    async def _enhance_answer(
        question: str,
        result: dict[str, Any],
        history: list[dict] | None = None,
    ) -> str | None:
        """Ask Qwen to phrase a natural answer over the query results."""
        data_json = json.dumps(result.get("data", []), ensure_ascii=False)
        snapshot_json = json.dumps(result.get("snapshot", {}), ensure_ascii=False)
        history_text = ""
        if history:
            lines = []
            for msg in history[-6:]:
                role = "用户" if msg.get("role") == "user" else "助手"
                lines.append(f"{role}：{str(msg.get('content', ''))[:300]}")
            history_text = "以下是本次会话的历史对话（供上下文参考）：\n" + "\n".join(lines) + "\n\n"
        prompt = (
            f"商家问题：{question}\n\n"
            f"{history_text}"
            f"以下是系统已从数据库查询到的真实数据（JSON）：\n{data_json}\n\n"
            f"以下是该工作空间的整体经营快照（JSON）：\n{snapshot_json}\n\n"
            "请优先基于以上真实数据回答。如果查询结果为空，可结合经营快照回答。"
            "若用户的问题与历史对话相关（如\"那退款呢\"\"刚才说的那个\"），请结合历史上下文理解。"
            "用简洁、专业的中文，不要编造数据，只输出回答本身。"
        )
        return await _call_qwen_generation(
            "你是一位专业的电商数据分析助手，回答要简洁、准确、口语化。",
            prompt,
            temperature=0.5,
        )

