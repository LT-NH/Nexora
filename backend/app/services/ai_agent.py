    @staticmethod
    async def _revenue_summary(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        now = datetime.now(timezone.utc)
        month_start = datetime(now.year, now.month, 1, tzinfo=timezone.utc)

        result = await db.execute(
            select(Order).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
                Order.created_at >= month_start,
            )
        )
        orders = result.scalars().all()

        total_revenue = sum(float(o.total or 0) for o in orders)
        daily: dict[str, float] = {}
        for o in orders:
            if o.created_at is not None:
                key = o.created_at.date().isoformat()
                daily[key] = daily.get(key, 0.0) + float(o.total or 0)

        # Build a continuous daily series from month start up to today.
        series = []
        for day in range(1, now.day + 1):
            date_str = f"{now.year:04d}-{now.month:02d}-{day:02d}"
            series.append({
                "label": f"{now.month}月{day}日",
                "value": _round2(daily.get(date_str, 0.0)),
            })

        answer = (
            f"本月（{now.year}年{now.month}月）营收 {_money(total_revenue)}，"
            f"共 {len(orders)} 笔有效订单。"
        )
        return {
            "intent": "revenue_summary",
            "answer_text": answer,
            "data": series,
            "chart_type": "line",
            "suggestion": (
                "建议对比上月同期数据，重点关注热销商品与转化率变化，"
                "及时发现增长或下滑趋势。"
            ),
        }

    @staticmethod
    async def _order_count(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        now = datetime.now(timezone.utc)
        today_start = datetime(now.year, now.month, now.day, tzinfo=timezone.utc)
        month_start = datetime(now.year, now.month, 1, tzinfo=timezone.utc)

        total = await db.scalar(
            select(func.count(Order.id)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
            )
        )
        month = await db.scalar(
            select(func.count(Order.id)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
                Order.created_at >= month_start,
            )
        )
        today = await db.scalar(
            select(func.count(Order.id)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
                Order.created_at >= today_start,
            )
        )
        total = int(total or 0)
        month = int(month or 0)
        today = int(today or 0)

        return {
            "intent": "order_count",
            "answer_text": (
                f"当前累计有效订单 {total} 笔；本月新增 {month} 笔，今日 {today} 笔。"
            ),
            "data": [
                {"label": "累计有效订单", "value": total},
                {"label": "本月订单", "value": month},
                {"label": "今日订单", "value": today},
            ],
            "chart_type": "number",
            "suggestion": (
                "若今日订单明显低于近期均值，建议检查流量渠道与促销活动效果。"
            ),
        }

    @staticmethod
    async def _refund_rate(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        refund_count = await db.scalar(
            select(func.count(Refund.id)).where(
                Refund.workspace_id == workspace_id,
                Refund.status.in_([RefundStatus.APPROVED, RefundStatus.COMPLETED]),
            )
        )
        total_orders = await db.scalar(
            select(func.count(Order.id)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
            )
        )
        refund_count = int(refund_count or 0)
        total_orders = int(total_orders or 0)
        rate = round(refund_count / total_orders * 100, 1) if total_orders else 0.0

        return {
            "intent": "refund_rate",
            "answer_text": (
                f"退款订单 {refund_count} 笔，占全部 {total_orders} 笔有效订单的 {rate:.1f}%。"
            ),
            "data": [
                {"label": "退款订单数", "value": refund_count},
                {"label": "总订单数", "value": total_orders},
                {"label": "退款率", "value": f"{rate:.1f}%"},
            ],
            "chart_type": "number",
            "suggestion": (
                "若退款率超过 5%，建议优先排查商品质量与物流时效问题，"
                "并对高频退款商品做下架或改进处理。"
            ),
        }

    @staticmethod
    async def _top_products(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        result = await db.execute(
            select(
                Product.name,
                func.sum(OrderItem.quantity),
                func.sum(OrderItem.total_price),
            )
            .join(OrderItem, OrderItem.product_id == Product.id)
            .join(Order, Order.id == OrderItem.order_id)
            .where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
            )
            .group_by(Product.id, Product.name)
            .order_by(func.sum(OrderItem.quantity).desc())
            .limit(5)
        )
        rows = result.all()
        data = [
            {
                "name": name,
                "value": int(quantity or 0),
                "revenue": _round2(float(revenue or 0)),
            }
            for name, quantity, revenue in rows
        ]

        if not data:
            answer = "暂无可统计的热销商品，建议先完善商品与订单数据。"
        else:
            top = data[0]
            answer = (
                f"热销商品 Top {len(data)}：榜首「{top['name']}」销量 {top['value']} 件，"
                f"销售额 {_money(top['revenue'])}。"
            )

        return {
            "intent": "top_products",
            "answer_text": answer,
            "data": data,
            "chart_type": "bar",
            "suggestion": (
                "为热销商品及时补货并优化详情页，可搭配套餐或满减提升客单价。"
            ),
        }

    @staticmethod
    async def _low_stock(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        result = await db.execute(
            select(Product)
            .where(
                Product.workspace_id == workspace_id,
                Product.stock <= Product.low_stock_threshold,
            )
            .order_by(Product.stock.asc())
            .limit(10)
        )
        products = result.scalars().all()
        data = [
            {
                "name": p.name,
                "stock": p.stock,
                "threshold": p.low_stock_threshold,
            }
            for p in products
        ]

        if not data:
            answer = "当前没有库存不足的商品，库存状况良好。"
        else:
            names = "、".join(p["name"] for p in data[:5])
            answer = (
                f"当前有 {len(data)} 个商品库存低于预警线：{names}。"
                if len(data) <= 5
                else f"当前有 {len(data)} 个商品库存低于预警线，前 5 个为：{names}。"
            )

        return {
            "intent": "low_stock",
            "answer_text": answer,
            "data": data,
            "chart_type": "list",
            "suggestion": (
                "建议优先为销量稳定但库存不足的商品安排补货，避免断货损失销售。"
            ),
        }

    @staticmethod
    async def _customer_insight(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        now = datetime.now(timezone.utc)
        result = await db.execute(
            select(Customer).where(Customer.workspace_id == workspace_id)
        )
        customers = result.scalars().all()
        total = len(customers)
        repeat = sum(1 for c in customers if c.total_orders >= 2)
        churned = sum(
            1
            for c in customers
            if c.last_order_at is not None and (now - c.last_order_at).days > 90
        )

        repeat_pct = round(repeat / total * 100, 1) if total else 0.0
        answer = (
            f"当前共有客户 {total} 人，其中复购客户（≥2 单）{repeat} 人，"
            f"占比 {repeat_pct:.1f}%；超过 90 天未下单的潜在流失客户 {churned} 人。"
        )
        return {
            "intent": "customer_insight",
            "answer_text": answer,
            "data": [
                {"name": "总客户", "value": total},
                {"name": "复购客户", "value": repeat},
                {"name": "潜在流失", "value": churned},
            ],
            "chart_type": "bar",
            "suggestion": (
                "对潜在流失客户发送唤醒优惠券，对复购客户建立会员权益，"
                "提升客户终身价值。"
            ),
        }

    @staticmethod
    async def _overview(db: AsyncSession, workspace_id: str) -> dict[str, Any]:
        total_revenue = await db.scalar(
            select(func.sum(Order.total)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
            )
        )
        total_orders = await db.scalar(
            select(func.count(Order.id)).where(
                Order.workspace_id == workspace_id,
                Order.status.notin_(_EXCLUDED_STATUSES),
            )
        )
        refund_count = await db.scalar(
            select(func.count(Refund.id)).where(
                Refund.workspace_id == workspace_id,
                Refund.status.in_([RefundStatus.APPROVED, RefundStatus.COMPLETED]),
            )
        )
        low_stock_count = await db.scalar(
            select(func.count(Product.id)).where(
                Product.workspace_id == workspace_id,
                Product.stock <= Product.low_stock_threshold,
            )
        )
        total_revenue = float(total_revenue or 0)
        total_orders = int(total_orders or 0)
        refund_count = int(refund_count or 0)
        low_stock_count = int(low_stock_count or 0)
        rate = round(refund_count / total_orders * 100, 1) if total_orders else 0.0

        answer = (
            f"店铺概览：累计营收 {_money(total_revenue)}，有效订单 {total_orders} 笔，"
            f"退款率 {rate:.1f}%，{low_stock_count} 个商品需要补货。"
        )
        return {
            "intent": "default",
            "answer_text": answer,
            "data": [
                {"label": "累计营收", "value": f"¥{total_revenue:,.2f}"},
                {"label": "有效订单", "value": total_orders},
                {"label": "退款率", "value": f"{rate:.1f}%"},
                {"label": "库存预警", "value": low_stock_count},
            ],
            "chart_type": "number",
            "suggestion": (
                "建议定期查看营收与退款率变化，及时调整商品结构与营销策略。"
            ),
        }

