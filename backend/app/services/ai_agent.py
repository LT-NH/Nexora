    @staticmethod
    async def intent_data(
        db: AsyncSession, workspace_id: str, question: str
    ) -> dict[str, Any]:
        """Run intent detection + real DB query, return the raw result dict.

        Unlike ``answer()`` this performs NO Qwen enhancement — it returns
        the pure query result so callers (e.g. streaming chat) can embed the
        real data into their own LLM context.
        """
        intent = BIAgent.detect_intent(question)

        handlers = {
            "revenue_summary": BIAgent._revenue_summary,
            "order_count": BIAgent._order_count,
            "refund_rate": BIAgent._refund_rate,
            "top_products": BIAgent._top_products,
            "low_stock": BIAgent._low_stock,
            "churn_customers": BIAgent._churn_customers,
            "customer_insight": BIAgent._customer_insight,
            "product_list": BIAgent._product_list,
            "order_list": BIAgent._order_list,
            "refund_list": BIAgent._refund_list,
            "customer_list": BIAgent._customer_list,
            "default": BIAgent._overview,
        }
        result = await handlers[intent](db, workspace_id)
        result["intent"] = intent
        # 附带全站快照，让 AI 对未命中的问题也有真实数据兜底
        try:
            result["snapshot"] = await BIAgent._workspace_snapshot(db, workspace_id)
        except Exception:
            result["snapshot"] = {}
        return result


